public class Contador{
	public static void main(String[] args){


		int Number = 20;
		while(Number<20){
			System.out.print(Number+ " ");
			Number++;
		}
		do {
			System.out.print(Number+ " ");
			Number++;
		}while(Number<21);
		
		for (int i = 20; i > 0; i--){
			System.out.print(i + " ");
		}

	}
}
